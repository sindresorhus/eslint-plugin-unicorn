		'globalThis.Iterator.from(values).filter(async value => value)',
		'Iterator.concat(first, second).some(async value => value)',
		'Iterator.zip([first, second]).every(async value => value)',
		'Iterator.zipKeyed({first, second}).find(async value => value)',
		'array.values().filter(async value => value)',
		'map.keys().some(async value => value)',
		'set.entries().every(async value => value)',
		'string.matchAll(pattern).forEach(async value => value)',
		'Iterator.from(values).map(value => value).take(2).filter(async value => value)',
		'const iterator = Iterator.from(values); iterator.filter(async value => value);',
		'const iterator = array.values(); iterator.forEach(async value => value);',
		'const callback = async value => value; Iterator.from(values).filter(callback);',
