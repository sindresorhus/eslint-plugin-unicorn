test.typescript({
	valid: [
		'Object.defineProperty(object, "property", {get: undefined as (() => void) | undefined} satisfies PropertyDescriptor);',
		'Object.defineProperty(object, "property", {get: (() => {})!} as PropertyDescriptor);',
		'const descriptor = {get: 1} as PropertyDescriptor; mutate(descriptor as PropertyDescriptor); Object.defineProperty(object, "property", descriptor!);',
	],
	invalid: [
		'Object.defineProperty(object, "property", {get: 1 as unknown} as PropertyDescriptor);',
		'Object.defineProperty(object, "property", <PropertyDescriptor>{get: 1});',
		'Object.defineProperty(object, "property", {get: 1} satisfies PropertyDescriptor);',
		'Object.defineProperty(object, "property", {get: 1}!);',
		'Object.defineProperties(object, {property: {get: 1} as PropertyDescriptor} as PropertyDescriptorMap);',
		'const descriptor = {get: 1} as PropertyDescriptor; Object.defineProperty(object, "property", descriptor!);',
		'const descriptor = {get: 1} satisfies PropertyDescriptor; const descriptors = {property: descriptor!} as PropertyDescriptorMap; Object.create(prototype, descriptors!);',
	].map(code => ({code, errors: 1})),
});

